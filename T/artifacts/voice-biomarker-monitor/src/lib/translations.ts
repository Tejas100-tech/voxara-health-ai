export { backendTranslations };

// ── Translation hook ──────────────────────────────────────────────────────
const tMap = translations as Record<string, TranslationMap>;
const btMap = backendTranslations as Record<string, BackendTranslations>;

export function t(key: string, lang: LanguageCode = "en"): string {
  return tMap[lang]?.[key] || translations.en[key] || key;
}

export function getBackendTranslation(key: string, lang: LanguageCode = "en"): string {
  return btMap[lang]?.[key] || backendTranslations.en[key] || key;
}

// ── Merge complete translations for all languages ──────────────────────
// This ensures ALL pages are fully translated in ALL supported languages
for (const [lang, langTranslations] of Object.entries(COMPLETE_TRANSLATIONS)) {
  if (lang !== "en") {
    const langCode = lang as LanguageCode;
    if (!translations[langCode]) {
      translations[langCode] = {};
    }
    Object.assign(translations[langCode], langTranslations);
  }
}
